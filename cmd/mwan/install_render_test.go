// networkMinPath is the network configuration these tests render from. It is
// the instance document the schema gate already validates, and it carries the
// gateway's provider set: att on table 100, webpass on 200, monkeybrains on
// 300, with the internal link on enmwanbr0.
const networkMinPath = "../../yang/instances/network-min.json"

// configsRendered reads one file as the configs Jinja template renders it for
// the testbed gateway. These are the bytes the deploy writes today, captured
// from mwan/config/sysctl-mwan.conf.j2, mwan/config/rt_tables.j2 and
// mwan/wanconfig/nghttpx-wanconfig.conf.j2 with that gateway's inventory
// values, so a rendering difference here is a difference on the host.
func configsRendered(t *testing.T, name string) []byte {
	t.Helper()
	content, err := os.ReadFile(filepath.Join("testdata", "configs-rendered", name))
	if err != nil {
		t.Fatalf("read the deployed rendering of %s: %v", name, err)
	}
	return content
}

// TestRenderedSysctlMatchesTheDeployedTemplate proves the binary renders the
// kernel tunable file the deploy writes today, setting for setting.
//
// Four comment lines differ, and only those four. The binary writes the file
// now, so the provenance line cannot credit Ansible, and the three lines that
// named this site's ISPs name the interface instead, because the same binary
// runs at a site with other ISPs. Every line that sets a value is identical,
// in the same order, which is what systemd-sysctl and the kernel read.
func TestRenderedSysctlMatchesTheDeployedTemplate(t *testing.T) {
	t.Parallel()
	deployed := string(configsRendered(t, "sysctl-mwan.conf"))
	commentChanges := map[string]string{
		"# Generated by Ansible - interface names are templated from group_vars":      "# Rendered by mwan install from config.toml and network.json",
		"# Disable SLAAC on Webpass interface (prevents unwanted autoconf addresses)": "# Disable SLAAC on enwebpass0 (prevents unwanted autoconf addresses)",
		"# Disable source validation on Webpass WAN (needed for policy routing)":      "# Disable source validation on enwebpass0 (needed for policy routing)",
		"# Disable source validation on AT&T WAN (needed for policy routing)":         "# Disable source validation on enatt0 (needed for policy routing)",
	}
	want := deployed
	for old, replacement := range commentChanges {
		if !strings.Contains(want, old+"\n") {
			t.Fatalf("the deployed rendering no longer carries the line %q", old)
		}
		want = strings.Replace(want, old+"\n", replacement+"\n", 1)
	}

	got, err := renderGatewayFile("sysctl-mwan.conf.tmpl", sysctlInputs{
		InternalIface:         "enmwanbr0",
		DisableSLAACIfaces:    []string{"enwebpass0"},
		DisableRPFilterIfaces: []string{"enwebpass0", "enatt0"},
	})
	if err != nil {
		t.Fatalf("render: %v", err)
	}

	if string(got) != want {
		t.Fatalf("rendered sysctl file differs from the deployed one:\n%s", lineDiff(want, string(got)))
	}
	// The comment lines are the only difference, so every setting must come
	// through unchanged even if the substitution above ever went wrong.
	deployedSettings := parseSysctlSettings([]byte(deployed))
	renderedSettings := parseSysctlSettings(got)
	if len(deployedSettings) != len(renderedSettings) {
		t.Fatalf("settings count = %d, want %d", len(renderedSettings), len(deployedSettings))
	}
	for i, setting := range deployedSettings {
		if renderedSettings[i] != setting {
			t.Errorf("setting %d = %+v, want %+v", i, renderedSettings[i], setting)
		}
	}
}

// TestRenderedRoutingTablesMatchTheDeployedTemplate proves the routing table
// file is byte for byte the one the deploy writes, with the provider tables
// read from the network configuration and the reserved tables from
// config.toml.
func TestRenderedRoutingTablesMatchTheDeployedTemplate(t *testing.T) {
	t.Parallel()
	want := configsRendered(t, "rt_tables")

	got, err := renderGatewayFile("rt_tables.tmpl", rtTablesInputs{
		Providers: []routingTable{
			{TableID: 100, Name: "att"},
			{TableID: 200, Name: "webpass"},
			{TableID: 300, Name: "monkeybrains"},
		},
		ReservedTables: []routingTable{
			{TableID: 400, Name: "cloudflared"},
			{TableID: 500, Name: "oob"},
		},
	})
	if err != nil {
		t.Fatalf("render: %v", err)
	}

	if !bytes.Equal(got, want) {
		t.Fatalf("rendered rt_tables differs from the deployed one:\n%s",
			lineDiff(string(want), string(got)))
	}
}

