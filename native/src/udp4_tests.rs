#[test]
fn frozen_ipv4_udp_nat_preserves_forward_and_inverse_bytes() {
    let sentinel = &CASES[0];
    for case in CASES {
        let direction = nat_direction(case);
        let view = decode(case.received).expect(case.name);
        let native = !case.forwarded.is_empty();
        assert_eq!(
            eligible(case.received, &view, &direction),
            native,
            "{}",
            case.name
        );
        assert_eq!(
            observe(case.received).eligible,
            u8::from(native),
            "{}",
            case.name
        );
        let mut returned = case.received.to_vec();
        restore(&mut returned, &view, &direction).expect(case.name);
        assert_eq!(returned, case.original, "{}", case.name);
        if native {
            let mut prepared = case.received.to_vec();
            forward(&mut prepared, &view, &direction).expect(case.name);
            assert_eq!(prepared, case.forwarded, "{}", case.name);
            let forwarded_view = decode(&prepared).expect(case.name);
            assert!(
                eligible(&prepared, &forwarded_view, &direction),
                "{}",
                case.name
            );
            restore_forwarded(&mut prepared, &view, &direction).expect(case.name);
            assert_eq!(prepared, case.original, "{}", case.name);
        } else {
            let mut next = sentinel.received.to_vec();
            let next_view = decode(&next).expect("next complete UDP frame");
            let next_direction = nat_direction(sentinel);
            assert!(eligible(&next, &next_view, &next_direction));
            forward(&mut next, &next_view, &next_direction).expect("forward after UDP exception");
            assert_eq!(next, sentinel.forwarded);
        }
    }
}

#[test]
fn truncated_ipv4_udp_nat_restores_only_complete_bounded_headers() {
    let case = &CASES[0];
    let direction = nat_direction(case);
    for length in 0..case.received.len() {
        let mut received = case.received[..length].to_vec();
        match decode(&received) {
            Ok(view) => {
                assert!(view.malformed());
                assert!(!eligible(&received, &view, &direction));
                restore(&mut received, &view, &direction).expect("bounded inverse UDP NAT");
                assert_eq!(received, case.original[..length]);
            }
            Err(error) => assert_eq!(error.code, libc::EBADMSG),
        }
    }
}

fn nat_direction(case: &UdpNatCase) -> MwanNativeDirection {
    let original = decode(case.original).expect("original UDP headers");
    let received = decode(case.received).expect("translated UDP headers");
    let mut direction = MwanNativeDirection {
        original: original.tuple(),
        translated: received.tuple(),
        original_source_mac: original.source_mac(),
        original_destination_mac: original.destination_mac(),
        output_source_mac: [2, 0x57, 0x50, 4, 3, 1],
        output_destination_mac: [0x24, 0x5e, 0xbe, 0x8e, 0x6b, 0xa5],
        output_mtu: 1500,
        ..MwanNativeDirection::default()
    };
    if !original.ports {
        let baseline = &CASES[0];
        direction.original = decode(baseline.original)
            .expect("complete original tuple")
            .tuple();
        direction.translated = decode(baseline.received)
            .expect("complete translated tuple")
            .tuple();
    }
    direction
}
